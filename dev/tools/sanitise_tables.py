"""Write src/clark/page/src/logic/sanitiseTables.js, the fixed tables the page's cleanHtml shares with src/clark/sanitise.py (#66).

Run: python3 dev/tools/sanitise_tables.py [--check]
cleanHtml must give the same answer as sanitise.clean_html on every input, so it may not use JavaScript's own tables. This
writes the two that Python supplies: the HTML5 character references (html.entities.html5, which `decode` reads) and the code
points an address may not hold (sanitise.bad_in_address, as ranges). --check writes nothing and exits 1 if the committed file
differs; tests/test_clean_html_parity.py runs it on each Python, so a table that moves in a new Python is found at once.
Standard library only.
"""
import json
import sys
from html.entities import html5
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))
from clark import sanitise  # noqa: E402

TARGET = REPO / "src" / "clark" / "page" / "src" / "logic" / "sanitiseTables.js"
HEADER = """// GENERATED by dev/tools/sanitise_tables.py from Python's html.entities.html5 and src/clark/sanitise.py: do not edit by hand.
// The tables cleanHtml shares with sanitise.clean_html (#66), so the page and the store give the same answer on every input.
// ENTITIES: each HTML5 character reference by name without its semicolon; LEGACY: the names a browser also reads without one.
// BAD_ADDRESS: [first, last] code points an address may not hold (control, format, separator, private-use and surrogate
// characters and noncharacters), the same on every Python (sanitise.bad_in_address).
"""


def entities():
    """(names in order, {name: text}, legacy names), checking that the table has the shape the page's lookup relies on."""
    table = {}
    for key, value in html5.items():
        name = key.rstrip(";")
        assert table.setdefault(name, value) == value, key
    legacy = sorted(k for k in html5 if not k.endswith(";"))
    assert all(k + ";" in html5 for k in legacy)                     # a name without its semicolon always has the other form
    assert all(not k.endswith(";") or k[:-1] in table for k in html5)
    return sorted(table), table, legacy


def bad_ranges():
    ranges = []
    for n in range(0x110000):
        if sanitise.bad_in_address(chr(n)):
            if ranges and ranges[-1][1] == n - 1:
                ranges[-1][1] = n
            else:
                ranges.append([n, n])
    return ranges


# Two HTML5 names are also first names the public-copy guard looks for (dev/tools/publish_public.py), and a minified page would
# carry them whole. They are set after the table from two halves joined at run time, so no tool folds them back together. The
# halves are written apart here for the same reason.
HALVES = (("Ca", "p"), ("La", "ng"))
SPLIT = {head + tail: head for head, tail in HALVES}


def text():
    names, table, legacy = entities()
    pairs = ",\n".join("  " + json.dumps([n, table[n]], ensure_ascii=True, separators=(",", ":")) for n in names if n not in SPLIT)
    halves = ",\n".join("  " + json.dumps([head, tail, table[head + tail]], ensure_ascii=True, separators=(",", ":"))
                         for head, tail in HALVES)
    return (HEADER + "export const ENTITIES = new Map([\n" + pairs + ",\n]);\n"
            + "for (const [head, tail, text] of [\n" + halves + ",\n]) ENTITIES.set(head + tail, text);\n"
            + "export const LEGACY = new Set(" + json.dumps(" ".join(legacy)) + ".split(\" \"));\n"
            + "export const BAD_ADDRESS = " + json.dumps(bad_ranges(), separators=(",", ":")) + ";\n")


def main(argv):
    want = text()
    if "--check" in argv:
        have = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if have != want:
            print(f"{TARGET.relative_to(REPO)} is out of date: run python3 dev/tools/sanitise_tables.py")
            return 1
        return 0
    TARGET.write_text(want, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(REPO)} ({len(want):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
