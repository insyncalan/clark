import test_publish_route as base

PIC = base64.b64encode(bytes(range(40))).decode()
CIRCLE = ".logo{background:url(data:image/png;base64,%s)}" % PIC
EVIL = "http://x.test/a.png"


def style(css):
    return "<style>" + css + "</style>"


class OddDataUrls(unittest.TestCase):
    def test_a_data_url_with_odd_characters_is_refused_as_a_picture(self):
        for body in ("AA/*AA", "AA)AA", "AA;AA", "AA'AA", "AA AA", "AA%20AA"):
            for q in ('"', "'"):
                css = ".logo{background:url(%sdata:image/png;base64,%s%s)}" % (q, body, q)
                with self.subTest(css):
                    with self.assertRaises(PublishError):
                        publish.check_brand(style(css))

    def test_a_slash_star_in_a_data_url_starts_no_comment_so_an_address_after_it_is_read(self):
        for url in ("url(data:image/png;base64,AA/*A)", 'url("data:image/png;base64,AA/*A")', "url('data:image/png;base64,AA/*A')"):
            css = ".a{background:%s}.b{background:url(%s)}/* */" % (url, EVIL)
            with self.subTest(css):
                with self.assertRaises(PublishError) as caught:
                    publish.check_brand(style(css))
                self.assertIn("would reach outside the file", str(caught.exception))

    def test_a_comment_beside_a_good_circle_is_fine(self):
        publish.check_brand(style(CIRCLE + "/* url(%s) */" % EVIL))
        publish.check_brand(style("/**//**/" + CIRCLE + "/**/"))


class BigFile(unittest.TestCase):
    """The shape of the real brand file, with invented names and generated bytes."""

    def make(self):
        font = lambda n: "@font-face{font-family:F%d;src:url(data:font/woff2;base64,%s) format('woff2')}\n" % (n, "QUJD" * 9000)
        head = "/* tokens: url() is only a word here */\n:root{--brand-navy:#123}\n"
        body = "".join(font(n) for n in range(1, 6))                                              # 5 url(
        body += CIRCLE + "\n:root{--art-home:url(data:image/png;base64,%s)}\n" % PIC             # 2 more url(, 2 data:image
        body += "/* see url(%s) */\n" % EVIL                                                      # the 9th url(, in a comment
        css = head + body
        pad = 207_532 - len("<style>") - len(css) - len("</style>") - len("/*  */")
        self.assertGreater(pad, 0)
        return style(css + "/* " + "n" * pad + " */")

    def test_it_has_the_shape_and_stays_inside_the_scan_budget(self):
        text = self.make()
        self.assertEqual((len(text), text.count("url("), text.count("data:image")), (207_532, 9, 2))
        publish.check_brand(text)                          # no PublishError, so ScanTooBig did not trigger
        work = publish.Work(size=len(text))
        for css in publish.style_texts(text, work):
            publish.css_findings(css, work)
            publish._picture_as_data(css, work)
        self.assertLess(work.n * 5, work.limit)
        self.assertEqual(publish.outside_addresses(text), [])

    def test_the_same_url_outside_the_comment_is_refused(self):
        with self.assertRaises(PublishError):
            publish.check_brand(self.make().replace("/* see url(%s) */" % EVIL, "see{background:url(%s)}" % EVIL))


class Route(unittest.TestCase):
    """Publish and preview through the real server, with a brand's tokens.css in a folder."""

    def rig(self, css):
        brand = Path(tempfile.mkdtemp(prefix="clark-brand-"))
        self.addCleanup(lambda: [p.unlink() for p in brand.iterdir()] or brand.rmdir())
        (brand / "tokens.css").write_text(css, encoding="utf-8")
        return base.Rig(self, branding=str(brand))

    def test_publish_and_preview_pass_with_the_circle(self):
        rig = self.rig(":root { --brand-navy: #123; }\n" + CIRCLE + "\n/* url(%s) */\n" % EVIL)
        status, got = rig.publish(to_client=False)
        self.assertEqual((status, got["ok"]), (200, True), got)
        status, got = rig.call("POST", "/api/preview", {"project": "PUB"})
        self.assertEqual((status, got["ok"]), (200, True), got)

    def test_an_address_shows_its_own_sentence_on_publish_and_preview(self):
        for css in ("a{background:url(%s)}" % EVIL, "@import url(x.css);", "a{background:url(//x.test/a.png)}"):
            rig = self.rig(css)
            for status, got in (rig.publish(to_client=False), rig.call("POST", "/api/preview", {"project": "PUB"})):
                self.assertEqual(status, 409, got)
                self.assertIn(publish_flow.MESSAGES["brand_address"], got["message"])
                self.assertNotIn("web link", got["message"])
            self.assertEqual((rig.everything_written(), rig.rows()), ([], []))

    def test_another_picture_shows_its_own_sentence_on_publish_and_preview(self):
        rig = self.rig("a{background:url(data:image/png;base64,%s)}" % PIC)
        for status, got in (rig.publish(to_client=False), rig.call("POST", "/api/preview", {"project": "PUB"})):
            self.assertEqual(status, 409, got)
            self.assertIn(publish_flow.MESSAGES["brand_picture"], got["message"])
            self.assertNotIn("web link", got["message"])
            self.assertNotIn(publish_flow.MESSAGES["brand_address"], got["message"])


